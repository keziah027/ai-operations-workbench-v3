"""通用包装特征：只报告可见表达及其原文证据，不评价真实身份或情绪。"""
import re

FEATURE_PATTERNS = {
    "身份标签": r"\b[ie][ns][tf][jp]\b|打工人|应届生|宝妈|大学生|[一二三四五六七八九十\d]+年[\u4e00-\u9fff]{0,5}经验|作为[\u4e00-\u9fff]{2,8}|创业者|咨询师|设计师|主理人",
    "痛点表达": r"内耗|焦虑|迷茫|困扰|踩坑|瓶颈|做不好|不会|怎么办|没时间|失眠|被拒|拖延|压力|委屈",
    "结果导向": r"提升|提高|实现|拿到|获得|成功|涨薪|加薪|上岸|逆袭|解决|变得|学会|节省|告别|从.{1,12}到",
    "情绪表达": r"治愈|开心|难过|崩溃|焦虑|感动|快乐|孤独|松弛|委屈|愤怒|幸福|后悔|讨厌|喜欢|心疼",
    "反常识": r"反常识|颠覆|你以为|没想到|竟然|恰恰相反|并不是|不是.{1,20}而是|越.{1,12}越",
    "故事型": r"那天|有一次|从前|故事|后来|没想到|直到.{1,15}才",
    "经历型": r"我曾|我在|我从|我的经历|亲身|亲历|复盘|经历|亲测|入职|离职|转行|实习|创业第",
    "干货清单": r"清单|合集|汇总|盘点|速查|一览|[\d一二三四五六七八九十]+[个条点步招种]|(?:^|\n)\s*[1-9][、.．）)]",
    "强观点": r"我认为|我坚持|必须|一定要|千万别|别再|绝对|真正的|最重要|我的观点|拒绝",
    "人群指向": r"写给|送给|适合|如果你|建议.{0,8}看|[ie][ns][tf][jp]|打工人|应届生|新手|小白|宝妈|大学生|职场人",
    "场景化表达": r"通勤|面试|开会|汇报|下班|上班|周末|睡前|独处|独居|旅行|约会|聚会|办公室|在家|出门|考前|开学|健身房",
    "提问式标题": r"[?？]|怎么|如何|为什么|哪[个种]",
    "包含数字": r"\d|[一二三四五六七八九十]+[个种步款招]",
    "教程表达": r"教程|步骤|教你|怎么做|手把手|攻略|操作方法",
    "感叹句式": r"[!！]",
}


def detect_features(title, body=""):
    evidence = {}
    for label, pattern in FEATURE_PATTERNS.items():
        found = []
        for source, value in [("标题", title), ("正文", body)]:
            if label in ["提问式标题", "包含数字", "感叹句式"] and source != "标题":
                continue
            excerpts = list(dict.fromkeys(m.group(0) for m in re.finditer(pattern, value, flags=re.I)))[:3]
            if excerpts:
                found.append(source + "：" + "、".join(excerpts))
        if found:
            evidence[label] = "；".join(found)
    return evidence
